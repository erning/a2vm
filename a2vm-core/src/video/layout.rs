/// Compute the RAM address for HGR scanline `y` (0-191).
///
/// HGR memory is interleaved:
///   addr = base + (y%8)*$400 + ((y/8)%8)*$80 + (y/64)*40
#[inline]
pub(crate) fn hgr_line_addr(base: usize, y: usize) -> usize {
    base + ((y & 7) << 10) + (((y >> 3) & 7) << 7) + (y >> 6) * 40
}
